#!/usr/bin/env python3
"""Write web/data.js from fleet.py, concerns.py and the knobs in bay_gen.py.

The Python files stay the source of truth. After editing them, run:  python3 export_web.py
warranty() and the generation logic are ported by hand in web/app.js; keep them in step with bay_gen.py.
"""
import json, os
import bay_gen as bg
from concerns import CONCERNS, HARD, SYSTEMS
from fleet import BRANDS, YEARS


def plain(x):
    if isinstance(x, (set, frozenset)):
        return sorted(x)
    if isinstance(x, dict):
        return {k: plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [plain(v) for v in x]
    return x


data = dict(
    table=[list(r) for r in bg.TABLE],          # brand, model, vtype, year, engine, base weight
    concerns=plain(CONCERNS), hard=plain(HARD), systems=SYSTEMS, brands=BRANDS, years=YEARS,
    kFarm=bg.K_FARM, kCity=bg.K_CITY, kCityBrand=bg.K_CITY_BRAND, typeNames=bg.TYPE_NAMES,
    days=bg.DAYS, daySpread=bg.DAY_SPREAD,
    yearSd=bg.YEAR_SD, partialLast=bg.PARTIAL_LAST, defaultMean=bg.DEFAULT_MEAN,
    milesPerYear=bg.MILES_PER_YEAR, today=bg.TODAY, serviceContract=bg.SERVICE_CONTRACT,
)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "web", "data.js")
with open(out, "w") as f:
    f.write("// Generated by export_web.py from fleet.py, concerns.py and bay_gen.py. Don't edit by hand.\n")
    f.write("const BAYGEN = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out}: {len(data['table'])} vehicle rows, {len(CONCERNS)} concerns, {len(HARD)} diag scenarios")
